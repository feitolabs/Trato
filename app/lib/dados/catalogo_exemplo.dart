/// Formulário do Novo pedido para a categoria escolhida (mesma estrutura da tela 11 do
/// protótipo; só o que é específico de Elétrica mantém voltagem).
FormularioPedido formularioDaCategoria(CategoriaServico c) {
  final eletrica = c.id == 'eletrica';
  return FormularioPedido(
    categoriaId: c.id,
    icone: c.icone,
    categoria: eletrica ? 'Elétrica · Tomadas e chuveiro' : c.nome,
    servicos: c.servicos.isEmpty ? ['Orçamento geral'] : c.servicos,
    servicosIniciais: {if (c.servicos.isNotEmpty) c.servicos.first},
    perguntaQuantidade: eletrica ? 'Quantas tomadas?' : 'Quantos itens ou ambientes?',
    dicaQuantidade: eletrica ? 'Conte só as que vão ser trocadas' : 'Uma estimativa já ajuda',
    quantidadeInicial: 1,
    perguntaVoltagem: 'Voltagem do chuveiro',
    voltagens: eletrica ? const ['220 V', '127 V', 'Não sei'] : const [],
    voltagemInicial: eletrica ? '220 V' : '',
    descricaoInicial: '',
    fotos: const [],
    prazos: const ['Até sexta, 30/10', 'Esta semana', 'Sem pressa'],
    faixas: const [
      FaixaPreco(minimoCentavos: 20000, maximoCentavos: 50000),
      FaixaPreco(minimoCentavos: 0, maximoCentavos: 20000),
      FaixaPreco(minimoCentavos: 50000, maximoCentavos: 100000),
    ],
    endereco: 'Casa · Savassi, Belo Horizonte',
    avisoEndereco: 'O endereço completo só aparece para o profissional que você contratar.',
    avisoPrazo: 'Você recebe até 5 orçamentos em 48 horas. Avisamos quando o prazo terminar.',
  );
}
