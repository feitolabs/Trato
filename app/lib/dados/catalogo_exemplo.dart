const _verificado = 'Verificado';
const _plus = 'Verificado Plus';

Avaliacao _av(String servico, double nota, String comentario, {String cliente = 'Cliente'}) =>
    Avaliacao(
      cliente: cliente,
      servico: servico,
      nota: nota,
      comentario: comentario,
      detalhes: 'Pontualidade ${nota.round()} · Qualidade ${nota.round()} · Limpeza ${nota.round()}',
    );

Profissional _p({
  required String id,
  required String nome,
  required String categoriaId,
  required String especialidade,
  required int concluidos,
  required double nota,
  required double km,
  required String regiao,
  required int precoCentavos,
  required String bio,
  required List<String> servicos,
  required List<Avaliacao> avaliacoes,
  String selo = _verificado,
  String? resposta,
  bool hoje = false,
  int desde = 2025,
  int avaliacoesTotal = 0,
  int conclusao = 97,
  List<String> verificacoes = const [
    'Documento e selfie com prova de vida',
    'Certidão de antecedentes',
  ],
}) {
  final partes = nome.split(' ');
  return Profissional(
    id: id,
    nome: nome,
    iniciais: '${partes.first[0]}${partes.last[0]}',
    verificacao: selo,
    especialidade: especialidade,
    servicosConcluidos: concluidos,
    nota: nota,
    distanciaKm: km,
    respostaCurta: resposta,
    atendeHoje: hoje,
    regiao: regiao,
    categoriaId: categoriaId,
    precoAPartirCentavos: precoCentavos,
    detalhe: DetalhePerfil(
      noTratoDesde: desde,
      totalAvaliacoes: avaliacoesTotal == 0 ? avaliacoes.length : avaliacoesTotal,
      taxaConclusao: conclusao,
      respondeEm: resposta == null ? '~3 horas' : '~${resposta.replaceAll('resp. em ', '')}',
      verificacoes: verificacoes,
      avaliacoes: avaliacoes,
      bio: bio,
      servicos: servicos,
      trabalhos: [for (final s in servicos.take(3)) s],
    ),
  );
}

